/* ── Main ─────────────────────────────────────────────────── */

function main() {
  console.log("=== Write Staging JSON → Source TypeScript Files ===\n");

  // ── Approvals ──
  const approvalsPath = path.join(STAGING_DIR, "approvals-ar.json");
  const approvalsData = JSON.parse(fs.readFileSync(approvalsPath, "utf-8"));
  console.log(`Approvals: ${approvalsData.length} entries from staging`);

  const approvalsTS = buildApprovalsFile(approvalsData);
  const approvalsOut = path.join(SRC_DIR, "approvals-ar.ts");
  fs.writeFileSync(approvalsOut, approvalsTS, "utf-8");
  console.log(`  ✓ Wrote ${approvalsOut}`);

  // ── Guides ──
  const guidesPath = path.join(STAGING_DIR, "guides-ar.json");
  const guidesData = JSON.parse(fs.readFileSync(guidesPath, "utf-8"));
  console.log(`Guides: ${guidesData.length} entries from staging`);

  const guidesTS = buildGuidesFile(guidesData);
  const guidesOut = path.join(SRC_DIR, "guides-ar.ts");
  fs.writeFileSync(guidesOut, guidesTS, "utf-8");
  console.log(`  ✓ Wrote ${guidesOut}`);

  // ── Services ──
  const servicesPath = path.join(STAGING_DIR, "services-ar.json");
  const servicesData = JSON.parse(fs.readFileSync(servicesPath, "utf-8"));
  console.log(`Services: ${servicesData.length} entries from staging`);

  const servicesTS = buildServicesFile(servicesData);
  const servicesOut = path.join(SRC_DIR, "services-ar.ts");
  fs.writeFileSync(servicesOut, servicesTS, "utf-8");
  console.log(`  ✓ Wrote ${servicesOut}`);

  console.log("\n=== Done ===");
}

main();
