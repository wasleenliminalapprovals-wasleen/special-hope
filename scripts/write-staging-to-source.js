/**
 * Phase 1.3 — Write Staging JSON Content into Source TypeScript Files
 *
 * Reads the DeepSeek-localized staging JSON files and writes them as
 * properly formatted TypeScript modules into src/data/*-ar.ts.
 *
 * Usage:
 *   node scripts/write-staging-to-source.js
 *
 * @see plans/arabic-content-overhaul-plan.md §1.3
 */

const fs = require("fs");
const path = require("path");

const STAGING_DIR = path.resolve(__dirname, "staging");
const SRC_DIR = path.resolve(__dirname, "..", "src", "data");

/* ── JSON → TypeScript converter ─────────────────────────── */

/**
 * Convert a JSON value to its TypeScript literal representation.
 * Handles strings, numbers, booleans, null, arrays, and plain objects.
 */
function toTypeScript(val, indent = 2) {
  const pad = " ".repeat(indent);
  const childPad = " ".repeat(indent + 2);

  if (val === null || val === undefined) {
    return "null";
  }

  if (typeof val === "string") {
    // Escape backslashes and single quotes for single-quoted strings
    // Dollar signs ($) are NOT special in single-quoted JS strings, only in template literals
    const escaped = val
      .replace(/\\/g, "\\\\")
      .replace(/'/g, "\\'")
      .replace(/\n/g, "\\n");

    return `'${escaped}'`;
  }

  if (typeof val === "number" || typeof val === "boolean") {
    return String(val);
  }

  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";

    // Check if all elements are simple (primitives)
    const allSimple = val.every(
      (v) =>
        v === null ||
        typeof v === "string" ||
        typeof v === "number" ||
        typeof v === "boolean"
    );

    if (allSimple) {
      // Single line for simple arrays
      const items = val.map((v) => toTypeScript(v, indent)).join(", ");
      return `[${items}]`;
    }

    // Multi-line for arrays of objects
    const items = val
      .map((v) => `${childPad}${toTypeScript(v, indent + 2)}`)
      .join(",\n");
    return `[\n${items},\n${pad}]`;
  }

  if (typeof val === "object") {
    const keys = Object.keys(val);
    if (keys.length === 0) return "{}";

    const props = keys
      .filter((k) => val[k] !== undefined)
      .map((k) => {
        const keyStr = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(k)
          ? k
          : `'${k}'`;
        return `${childPad}${keyStr}: ${toTypeScript(val[k], indent + 2)}`;
      })
      .join(",\n");
    return `{\n${props},\n${pad}}`;
  }

  return String(val);
}

/**
 * Build the TypeScript file content for approvals.
 */
function buildApprovalsFile(entries) {
  const lines = [
    "/**",
    " * Arabic approval data — DeepSeek-localized content.",
    " * Auto-generated by scripts/write-staging-to-source.js",
    " *",
    " * @see src/data/approvals.ts for English source",
    " * @see plans/arabic-content-overhaul-plan.md §1.3",
    " */",
    "",
    'import type { ApprovalArabicEntry } from "@/types";',
    "",
    "export const approvals: ApprovalArabicEntry[] = [",
  ];

  for (let i = 0; i < entries.length; i++) {
    const entry = entries[i];
    const ar = entry.ar;

    // Build the ar object content
    const arProps = [
      `  slug: ${toTypeScript(ar.slug)}`,
      `  name: ${toTypeScript(ar.name)}`,
      `  shortName: ${toTypeScript(ar.shortName)}`,
      `  authorityFull: ${toTypeScript(ar.authorityFull)}`,
      `  authorityAbbr: ${toTypeScript(ar.authorityAbbr)}`,
      `  primaryKeyword: ${toTypeScript(ar.primaryKeyword)}`,
      `  secondaryKeywords: ${toTypeScript(ar.secondaryKeywords, 6)}`,
      `  directAnswer: ${toTypeScript(ar.directAnswer)}`,
      `  description: ${toTypeScript(ar.description)}`,
      `  whoNeedsIt: ${toTypeScript(ar.whoNeedsIt, 6)}`,
      `  documents: ${toTypeScript(ar.documents, 6)}`,
      `  process: ${toTypeScript(ar.process, 6)}`,
      `  timelineTable: ${toTypeScript(ar.timelineTable, 6)}`,
      `  rejectionReasons: ${toTypeScript(ar.rejectionReasons, 6)}`,
      `  caseStudy: ${toTypeScript(ar.caseStudy, 6)}`,
      `  whyChooseUs: ${toTypeScript(ar.whyChooseUs, 6)}`,
      `  faqs: ${toTypeScript(ar.faqs, 6)}`,
      `  stats: ${toTypeScript(ar.stats == null ? [] : ar.stats, 6)}`,
      `  typicalTimeline: ${toTypeScript(ar.typicalTimeline == null ? '' : ar.typicalTimeline)}`,
      `  typicalCostRange: ${toTypeScript(ar.typicalCostRange == null ? '' : ar.typicalCostRange)}`,
    ];

    lines.push(
      "  {",
      `    slug: ${toTypeScript(entry.slug)},`,
      "    ar: {"
    );
    arProps.forEach((p) => lines.push(`      ${p},`));
    lines.push("    },");
    lines.push("  },");

    // Add blank line between entries (but not after last)
    if (i < entries.length - 1) {
      lines.push("");
    }
  }

  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

/**
 * Build the TypeScript file content for guides.
 */
function buildGuidesFile(entries) {
  const lines = [
    "/**",
    " * Arabic guide data — DeepSeek-localized content.",
    " * Auto-generated by scripts/write-staging-to-source.js",
    " *",
    " * @see src/data/guides.ts for English source",
    " * @see plans/arabic-content-overhaul-plan.md §1.3",
    " */",
    "",
    'import type { GuideArabicEntry } from "@/types";',
    "",
    "export const guides: GuideArabicEntry[] = [",
  ];

  for (let i = 0; i < entries.length; i++) {
    const entry = entries[i];
    const ar = entry.ar;

    const arProps = [
      `  slug: ${toTypeScript(ar.slug)}`,
      `  title: ${toTypeScript(ar.title)}`,
      `  description: ${toTypeScript(ar.description)}`,
      `  primaryKeyword: ${toTypeScript(ar.primaryKeyword)}`,
      `  secondaryKeywords: ${toTypeScript(ar.secondaryKeywords, 6)}`,
      // question and answer are optional
    ];

    if (ar.question !== undefined && ar.question !== null) {
      arProps.push(`  question: ${toTypeScript(ar.question)}`);
    }
    if (ar.answer !== undefined && ar.answer !== null) {
      arProps.push(`  answer: ${toTypeScript(ar.answer)}`);
    }

    arProps.push(`  content: ${toTypeScript(ar.content, 6)}`);

    lines.push(
      "  {",
      `    slug: ${toTypeScript(entry.slug)},`,
      "    ar: {"
    );
    arProps.forEach((p) => lines.push(`      ${p},`));
    lines.push("    },");
    lines.push("  },");

    if (i < entries.length - 1) {
      lines.push("");
    }
  }

  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

