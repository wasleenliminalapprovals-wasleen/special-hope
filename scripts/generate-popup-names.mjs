#!/usr/bin/env node
/**
 * generate-popup-names.mjs — build-time generator for `src/lib/popup-service-names.ts`.
 *
 * Reads the slug → clean shortName mapping from `src/data/approvals.ts` (69 entries,
 * each with `shortName`) and `src/data/services.ts` (7 entries, fall back to `name`),
 * then emits a tiny (~2KB) client-safe map. This is the single source of truth for
 * popup `serviceInterest` copy — it avoids importing the 7,400-line approvals.ts into
 * the client bundle and guarantees clean, natural popup copy on every page.
 *
 * Usage (from the project root):
 *   node scripts/generate-popup-names.mjs
 *
 * Re-run after ANY edit to src/data/approvals.ts or src/data/services.ts. Never
 * hand-edit the generated file. See plans/dynamic-popup-implementation-plan.md §3/§4.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const APPROVALS_PATH = resolve(ROOT, "src/data/approvals.ts");
const SERVICES_PATH = resolve(ROOT, "src/data/services.ts");
const OUTPUT_PATH = resolve(ROOT, "src/lib/popup-service-names.ts");

/**
 * Extract { slug, shortName } pairs from a data file.
 *
 * Approvals records (consistent formatting — see src/data/approvals.ts):
 *   {
 *     slug: "dubai-municipality-building-permit",
 *     name: "Dubai Municipality Building Permit",
 *     shortName: "DM Building Permit",
 * Services records have NO shortName — we fall back to `name`.
 *
 * The shortName group is optional; when absent the record is still captured and
 * `shortName` resolves to `name` (used by services).
 */
function extractNames(filePath, fallbackToName) {
  const source = readFileSync(filePath, "utf8");

  const entryRe =
    /slug:\s*"([^"]+)",\s*\n\s*name:\s*"([^"]+)",(?:\s*\n\s*shortName:\s*"([^"]*)")?/g;

  const map = new Map();
  let match;
  while ((match = entryRe.exec(source)) !== null) {
    const slug = match[1];
    const name = match[2];
    const shortName = match[3];
    map.set(slug, shortName && shortName.trim().length > 0 ? shortName.trim() : name);
    void fallbackToName; // kept for readability; fallback is expressed above
  }
  return map;
}

function main() {
  const approvals = extractNames(APPROVALS_PATH, true);
  const services = extractNames(SERVICES_PATH, true);

  const combined = new Map([...approvals, ...services]);
  const sortedKeys = [...combined.keys()].sort();

  if (sortedKeys.length === 0) {
    console.error(
      "generate-popup-names: no entries found — check that src/data/approvals.ts and " +
        "src/data/services.ts still match the expected slug/name/shortName format.",
    );
    process.exit(1);
  }

  const lines = sortedKeys.map(
    (slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(combined.get(slug))},`,
  );

  const output = `/**
 * AUTO-GENERATED by scripts/generate-popup-names.mjs — DO NOT EDIT.
 *
 * slug → clean shortName map used for popup copy (serviceInterest / WhatsApp pre-fill).
 * Source: src/data/approvals.ts (shortName) + src/data/services.ts (name).
 * Re-run \`node scripts/generate-popup-names.mjs\` after editing either data file.
 */
export const POPUP_SERVICE_NAMES: Record<string, string> = {
${lines.join("\n")}
} as const;
`;

  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, output, "utf8");

  console.log(
    `generate-popup-names: wrote ${sortedKeys.length} entries (${approvals.size} approvals + ${services.size} services) → src/lib/popup-service-names.ts`,
  );
}

main();
