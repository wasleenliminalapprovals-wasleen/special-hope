/**
 * Case Study Detail Page — /case-studies/{slug} (EN)
 *
 * Dynamic route rendering a single case study from `src/data/case-studies.ts`.
 * Follows the 13-section template (Part 5.1) in exact order:
 *   1 Hero (direct answer + breadcrumb)    8 Planned vs Actual
 *   2 Stats (4 facts)                      9 Results (+ ProTip 2)
 *   3 At a Glance (table)                   [mid CTA — Part 8]
 *   4 Challenge (+ ProTip 1)              10 FAQ (CSS accordion)
 *   5 Timeline (flagship SVG)             11 Related
 *   6 Steps (HowTo <ol>)                  12 Final CTA (reuses CTASection)
 *   7 Documents (table)                   13 Schema (JSON-LD)
 *
 * Schema stack (Part 12) is generated by `caseStudySchemaStack()` from
 * `src/lib/case-studies.ts`: Article + WebPage + BreadcrumbList +
 * (FAQPage) + (HowTo) + ImageObject*. Visible text = schema text
 * byte-for-byte (RULE 3 / Part 12 gate).
 *
 * Canonical + hreflang (en-AE / ar-AE / x-default) via `hreflangAlternates()`.
 *
 * @see plans/case-studies-mega-plan.md Part 5.1 / Part 8 / Part 12
 */

import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { caseStudies } from "@/data/case-studies";
import { CASE_STUDIES_HUB_PATH, caseStudySchemaStack, caseStudyUrl } from "@/lib/case-studies";
import { SITE } from "@/lib/constants";
import { hreflangAlternates } from "@/lib/locale";
import type { BreadcrumbItem } from "@/lib/schema";

/* ── Case-study styles (design tokens, reveal/choreography) ── */
import "@/components/case-studies/case-studies.css";

/* ── Section Components (Part 5.1, 12 sections) ───────────── */
import CaseStudyHero from "@/components/case-studies/CaseStudyHero";
import CaseStudyPhoto from "@/components/case-studies/CaseStudyPhoto";
import CaseStudyStats from "@/components/case-studies/CaseStudyStats";
import CaseStudyAtGlance from "@/components/case-studies/CaseStudyAtGlance";
import CaseStudyChallenge from "@/components/case-studies/CaseStudyChallenge";
import CaseStudyTimeline from "@/components/case-studies/CaseStudyTimeline";
import CaseStudySteps from "@/components/case-studies/CaseStudySteps";
import CaseStudyDocuments from "@/components/case-studies/CaseStudyDocuments";
import CaseStudyBeforeAfter from "@/components/case-studies/CaseStudyBeforeAfter";
import CaseStudyResults from "@/components/case-studies/CaseStudyResults";
